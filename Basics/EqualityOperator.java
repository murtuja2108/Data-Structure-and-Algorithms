package Basics;

public class EqualityOperator {
    public static void main(String[] args){
        // Equality Operator -> (== ,!=)
        int a=5;
        int b=2;
        int c=2;
        System.out.println(a==b);
        System.out.println(a!=b);
        System.out.println(b==c);
        System.out.println(b!=c);
    }
}
