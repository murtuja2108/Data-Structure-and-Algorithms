package Basics;

public class UpdationOfVar {
    public static void main(String[] args)
    {
        int x=10;
        System.out.println(x);
        x=20;
        System.out.println(x);
        x=x+3;//x+=3;
        System.out.println(x);
        x=x-12;//x-=12;
        System.out.println(x);
    }
}
