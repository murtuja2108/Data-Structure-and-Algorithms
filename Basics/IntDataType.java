package Basics;

public class IntDataType {
    public static void main(String[] args){
        int x=30;//By default every integer value is considered as int type
        int y=20;
        long l=20l;//For long suffixing l/L is mandatory.
        System.out.println(x+y);
        System.out.println(x-y);
        System.out.println(x*y);
        System.out.println(x/y);
        System.out.println(x%y);
    }
}
