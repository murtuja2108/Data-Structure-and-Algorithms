package Basics;

public class DivitionMethod {
    public static void main(String[] args) {
        // int/int=int
        System.out.println(5/2);
        // double/double=double
        System.out.println(5.0/2.0);
        // int/double=double
        System.out.println(5/2.0);
        // double/int=double
        System.out.println(5.0/2);
    }
}
